#!/usr/bin/env python3
"""Turn Gogh terminal palettes into contrast-checked web colour schemes.

    python3 -I gen_schemes.py THEMES_JSON [options]

THEMES_JSON is Gogh's data/themes.json (https://github.com/Gogh-Co/Gogh, MIT / Apache-2.0),
downloaded once:  gh api repos/Gogh-Co/Gogh/contents/data/themes.json --jq .download_url | xargs curl -sSLo themes.json

Outputs (each optional):
  --css FILE          write the curated blocks between the @gogh:begin / @gogh:end markers
                      in FILE (e.g. the app's copy of gogh-derive.css); creates nothing else
  --css-out FILE      or write the blocks to their own file
  --manifest FILE     curated list for gogh-schemes.js configure({curated}) — JSON
  --palettes FILE     every Gogh palette, slimmed (~140 KB, ~50 KB gzipped), for the
                      "any scheme" search
  --curated FILE      which schemes to ship: JSON {"Gogh name": null | "color_0N" |
                      {"accent": "color_0N", "name": "Display name"}}. Default:
                      assets/curated-default.json next to this script
  --selector PATTERN  CSS selector per scheme, {id} is replaced (default html[data-scheme="{id}"])
  --check             only print the contrast report

The colour logic is the same as build() in gogh-schemes.js (keep the two in step):
surfaces as in gogh-derive.css, text 7:1, muted / accent / red / text-on-accent 4.5:1,
failing colours pulled towards white (dark) / black (light) in 5% steps. A curated
scheme is DROPPED if its text would have to move more than 40% (it stops being that
scheme); the in-browser search never drops, it tells the user instead.
"""
import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEXT_MIN, FG_MIN, FG_MAX_NUDGE = 4.5, 7.0, 40
WHITE, BLACK = (1, 1, 1), (0, 0, 0)
BEGIN, END = '/* @gogh:begin — generated by gen_schemes.py, do not edit */', '/* @gogh:end */'


def rgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def hexs(c):
    return '#' + ''.join(f'{round(max(0, min(1, v)) * 255):02X}' for v in c)


def mix(a, b, pa):                      # color-mix(in srgb, a pa, b)
    return tuple(x * pa + y * (1 - pa) for x, y in zip(a, b))


def lum(c):
    lin = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in c]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def worst(c, bgs):
    return min(contrast(c, b) for b in bgs)


def nudge(c, bgs, towards, target=TEXT_MIN):
    for step in range(0, 101, 5):
        out = mix(towards, c, step / 100)
        if worst(out, bgs) >= target:
            return out, step
    return out, 100


def slug(name):
    return re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')


def build(t, accent_slot, display=None):
    dark = t['variant'] == 'dark'
    bg, fg0 = rgb(t['background']), rgb(t['foreground'])
    toward, toward_name = (WHITE, 'white') if dark else (BLACK, 'black')
    notes = []

    def surfaces(fg):
        return [bg, mix(fg, bg, .06), mix(fg, bg, .10)] if dark else \
               [bg, mix(WHITE, bg, .65), mix(WHITE, bg, .35)]

    for fg_step in range(0, FG_MAX_NUDGE + 1, 5):
        fg = mix(toward, fg0, fg_step / 100)
        bgs = surfaces(fg)
        if worst(fg, bgs) >= FG_MIN:
            break
    fg_c = worst(fg, bgs)
    if fg_step:
        notes.append(f'fg {worst(fg0, surfaces(fg0)):.2f}→{fg_c:.2f} (+{fg_step}% {toward_name})')
    for pct in range(72, 101, 2):
        muted = mix(fg, bg, pct / 100)
        if worst(muted, bgs) >= TEXT_MIN:
            break
    muted_c = worst(muted, bgs)
    fixed = {}
    for key, slot in (('accent', accent_slot or 'color_05'), ('red', 'color_02')):
        c0 = rgb(t[slot])
        c, step = nudge(c0, bgs, toward)
        if step:
            notes.append(f'{key} {worst(c0, bgs):.2f}→{worst(c, bgs):.2f} (+{step}% {toward_name})')
        fixed[key] = c
    accent, red = fixed['accent'], fixed['red']
    cands = [bg, WHITE, BLACK] if dark else [WHITE, bg, BLACK]
    on = next((c for c in cands if contrast(c, accent) >= TEXT_MIN), max(cands, key=lambda c: contrast(c, accent)))
    on_c = contrast(on, accent)
    name = display or t['name']
    return {
        'id': slug(name), 'name': name, 'gogh': t['name'], 'dark': dark,
        'bg': hexs(bg), 'fg': hexs(fg), 'muted': hexs(muted), 'accent': hexs(accent), 'on': hexs(on),
        'red': hexs(red), 'green': t['color_03'].upper(), 'yellow': t['color_04'].upper(),
        'blue': t['color_05'].upper(),
        'report': f'fg {fg_c:5.2f}  muted {muted_c:5.2f}  accent {worst(accent, bgs):5.2f}  on-accent {on_c:5.2f}',
        'notes': notes, 'ok': fg_c >= FG_MIN and muted_c >= TEXT_MIN and on_c >= TEXT_MIN,
    }


def css_block(s, selector):
    sel = selector.replace('{id}', s['id'])
    return (f'  /* Gogh: {s["gogh"]} */\n  {sel} {{\n'
            f'    --s-bg: {s["bg"]};  --s-fg: {s["fg"]};  --s-muted: {s["muted"]};\n'
            f'    --s-accent: {s["accent"]};  --s-on-accent: {s["on"]};\n'
            f'    --s-red: {s["red"]};  --s-green: {s["green"]};  --s-yellow: {s["yellow"]};  --s-blue: {s["blue"]};\n'
            f'  }}\n')


def replace_between(path, body):
    text = path.read_text()
    pat = re.compile(rf'({re.escape(BEGIN)}\n).*?([ \t]*{re.escape(END)})', re.S)
    if not pat.search(text):
        sys.exit(f'markers not found in {path}:\n  {BEGIN}\n  {END}')
    path.write_text(pat.sub(lambda m: m.group(1) + body.rstrip('\n') + '\n' + m.group(2), text, count=1))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('themes_json')
    ap.add_argument('--curated', default=str(HERE.parent / 'assets' / 'curated-default.json'))
    ap.add_argument('--css'); ap.add_argument('--css-out'); ap.add_argument('--manifest'); ap.add_argument('--palettes')
    ap.add_argument('--selector', default='html[data-scheme="{id}"]')
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()

    themes = {t['name']: t for t in json.loads(Path(a.themes_json).read_text())}
    curated = json.loads(Path(a.curated).read_text())
    missing = [n for n in curated if n not in themes]
    if missing:
        sys.exit(f'not in Gogh data (check spelling against themes.json): {missing}')
    built = []
    for name, spec in curated.items():
        spec = spec if isinstance(spec, dict) else {'accent': spec}
        built.append(build(themes[name], spec.get('accent'), spec.get('name')))
    for s in built:
        print(f'{"ok  " if s["ok"] else "DROP"} {s["name"]:24} {"dark " if s["dark"] else "light"}  {s["report"]}  {"; ".join(s["notes"])}')
    keep = sorted((s for s in built if s['ok']), key=lambda s: (not s['dark'], s['name'].lower()))
    print(f'\n{len(keep)} of {len(built)} schemes pass')
    if a.check:
        return
    blocks = ''.join(css_block(s, a.selector) for s in keep)
    if a.css:
        replace_between(Path(a.css), blocks); print('wrote', a.css)
    if a.css_out:
        Path(a.css_out).write_text(blocks); print('wrote', a.css_out)
    if a.manifest:
        Path(a.manifest).write_text(json.dumps([{'id': s['id'], 'name': s['name'], 'dark': s['dark'],
            'swatch': [s['bg'], s['fg'], s['accent']]} for s in keep], ensure_ascii=False, indent=1) + '\n')
        print('wrote', a.manifest)
    if a.palettes:
        rows = []
        for t in sorted(themes.values(), key=lambda t: t['name'].lower()):
            cols = [t['background'], t['foreground']] + [t[f'color_0{i}'] for i in range(1, 9)]
            rows.append([t['name'], 1 if t['variant'] == 'dark' else 0] + [c.lstrip('#').upper() for c in cols])
        Path(a.palettes).parent.mkdir(parents=True, exist_ok=True)
        Path(a.palettes).write_text(json.dumps({'source': 'Gogh — https://github.com/Gogh-Co/Gogh — MIT / Apache-2.0',
            'fields': ['name', 'dark', 'background', 'foreground'] + [f'color_0{i}' for i in range(1, 9)],
            'schemes': rows}, ensure_ascii=False, separators=(',', ':')) + '\n')
        print('wrote', a.palettes, f'({len(rows)} palettes)')


if __name__ == '__main__':
    main()
